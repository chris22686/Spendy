import { useMemo, useRef } from 'react';
import { useApp, formatMoney, getMonthExpenses, getCategoryTotals, getTotalSpent } from '../store';
import { BookOpen, Download, TrendingUp, Star, AlertTriangle, Award, Flame } from 'lucide-react';
import { format, startOfMonth, endOfMonth, eachDayOfInterval } from 'date-fns';
import { BarChart, Bar, XAxis, YAxis, Tooltip, ResponsiveContainer, PieChart, Pie, Cell } from 'recharts';

export default function MonthlyStory() {
  const { state } = useApp();
  const { expenses, categories, monthlyIncome } = state;
  const storyRef = useRef(null);

  const now = new Date();
  const monthName = format(now, 'MMMM yyyy');
  const monthExp = useMemo(() => getMonthExpenses(expenses), [expenses]);
  const totalSpent = useMemo(() => getTotalSpent(monthExp), [monthExp]);
  const savings = Math.max(0, monthlyIncome - totalSpent);
  const catTotals = useMemo(() => getCategoryTotals(monthExp, categories), [monthExp, categories]);

  const dailySpend = useMemo(() => {
    const start = startOfMonth(now);
    const end   = endOfMonth(now);
    const days  = eachDayOfInterval({ start, end });
    return days.map(d => {
      const dayStr = format(d, 'yyyy-MM-dd');
      const dayExps = monthExp.filter(e => e.date === dayStr);
      return {
        date: dayStr,
        label: format(d, 'MMM d'),
        total: dayExps.reduce((s, e) => s + e.amount, 0),
        count: dayExps.length,
        expenses: dayExps,
      };
    }).filter(d => d.total > 0);
  }, [monthExp]);

  const topSpendDay  = dailySpend.reduce((max, d) => d.total > max.total ? d : max, dailySpend[0] || { total: 0, label: '—', count: 0 });
  const bestSaveDay  = dailySpend.reduce((min, d) => d.total < min.total ? d : min, dailySpend[0] || { total: 0, label: '—', count: 0 });
  const topCategory  = catTotals[0] || { name: '—', icon: '📦', amount: 0, color: '#1b4332' };
  const avgDailySpend = dailySpend.length > 0 ? totalSpent / dailySpend.length : 0;

  const unusualDays = dailySpend.filter(d => d.total > avgDailySpend * 2);
  const recurringTotal = monthExp.filter(e => e.recurring).reduce((s, e) => s + e.amount, 0);

  const handleExport = () => {
    const text = [
      `📊 Monthly Financial Story — ${monthName}`,
      `═════════════════════════════════════════`,
      ``,
      `💸 TOTAL SPENT: ${formatMoney(totalSpent)}`,
      `💰 NET SAVINGS: ${formatMoney(savings)}`,
      `📅 MONTHLY INCOME: ${formatMoney(monthlyIncome)}`,
      ``,
      `🔥 TOP SPENDING DAY: ${topSpendDay.label} (${formatMoney(topSpendDay.total)})`,
      `✅ BEST SAVINGS DAY: ${bestSaveDay.label} (${formatMoney(bestSaveDay.total)})`,
      `🏆 HIGHEST OUTFLOW: ${topCategory.icon} ${topCategory.name} — ${formatMoney(topCategory.amount)}`,
      ``,
      `📦 CATEGORY SPLIT:`,
      ...catTotals.map(c => `  ${c.icon} ${c.name}: ${formatMoney(c.amount)}`),
      ``,
      `⚠️ UNUSUAL OUTFLOW SPIKES: ${unusualDays.length > 0 ? unusualDays.map(d => `${d.label} (${formatMoney(d.total)})`).join(', ') : 'None detected'}`,
      ``,
      `🔁 RECURRING EXPENSES / SUBSCRIPTIONS: ${formatMoney(recurringTotal)}/mo`,
      ``,
      `Generated by Spendy App on ${format(now, 'PPPp')}`,
    ].join('\n');

    const blob = new Blob([text], { type: 'text/plain' });
    const url  = URL.createObjectURL(blob);
    const a    = document.createElement('a');
    a.href = url;
    a.download = `Spendy-Story-${format(now, 'yyyy-MM')}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const CHART_COLORS = ['#1b4332','#2d6a4f','#40916c','#52b788','#d97706','#0284c7','#e11d48','#7c3aed'];

  return (
    <div className="space-y-6" ref={storyRef}>
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl sm:text-3xl font-extrabold text-[#14261c] tracking-tight">Monthly Financial Story</h1>
          <p className="text-[#65776c] text-sm mt-0.5 font-medium">Narrative summary of your performance in {monthName}</p>
        </div>
        <button
          onClick={handleExport}
          className="flex items-center gap-2 px-5 py-2.5 bg-[#1b4332] hover:bg-[#245740] active:scale-98 text-white rounded-xl text-sm font-bold shadow-md shadow-[#1b4332]/25 transition-all cursor-pointer self-start sm:self-auto"
        >
          <Download size={16} strokeWidth={2.4} />
          <span>Export Story</span>
        </button>
      </div>

      <div className="rounded-3xl bg-gradient-to-br from-[#133928] via-[#1b4332] to-[#2d6a4f] border border-[#2d6a4f]/50 p-6 sm:p-8 text-white shadow-xl shadow-[#1b4332]/20 relative overflow-hidden">
        <div className="flex items-center gap-3 mb-6">
          <div className="w-11 h-11 rounded-2xl bg-white/10 backdrop-blur-md border border-white/20 flex items-center justify-center text-[#a7e8c2]">
            <BookOpen size={22} />
          </div>
          <div>
            <h2 className="text-base font-extrabold text-white">{monthName} Chronicle</h2>
            <p className="text-xs text-[#a0cfb2] font-medium">{monthExp.length} transactions recorded across {catTotals.length} active categories</p>
          </div>
        </div>

        <div className="grid grid-cols-2 sm:grid-cols-4 gap-4">
          <div className="text-center p-3.5 rounded-2xl bg-white/5 border border-white/10">
            <p className="text-xl sm:text-2xl font-extrabold text-[#fecaca]">{formatMoney(totalSpent)}</p>
            <p className="text-xs text-[#a0cfb2] font-semibold mt-1">Total Spent</p>
          </div>
          <div className="text-center p-3.5 rounded-2xl bg-white/5 border border-white/10">
            <p className="text-xl sm:text-2xl font-extrabold text-[#bbf7d0]">{formatMoney(savings)}</p>
            <p className="text-xs text-[#a0cfb2] font-semibold mt-1">Net Saved</p>
          </div>
          <div className="text-center p-3.5 rounded-2xl bg-white/5 border border-white/10">
            <p className="text-xl sm:text-2xl font-extrabold text-[#ffffff]">{monthExp.length}</p>
            <p className="text-xs text-[#a0cfb2] font-semibold mt-1">Transactions</p>
          </div>
          <div className="text-center p-3.5 rounded-2xl bg-white/5 border border-white/10">
            <p className="text-xl sm:text-2xl font-extrabold text-[#99f6e4]">
              {monthlyIncome > 0 ? ((savings / monthlyIncome) * 100).toFixed(1) : 0}%
            </p>
            <p className="text-xs text-[#a0cfb2] font-semibold mt-1">Savings Rate</p>
          </div>
        </div>
      </div>

      <div className="grid sm:grid-cols-2 lg:grid-cols-4 gap-4">
        <HighlightCard
          icon={<Flame size={20} className="text-[#dc2626]" />}
          label="Peak Outflow Day"
          value={topSpendDay.label || '—'}
          sub={formatMoney(topSpendDay.total)}
        />
        <HighlightCard
          icon={<Star size={20} className="text-[#1b4332]" />}
          label="Best Savings Day"
          value={bestSaveDay.label || '—'}
          sub={`Only ${formatMoney(bestSaveDay.total)}`}
        />
        <HighlightCard
          icon={<Award size={20} className="text-[#2d6a4f]" />}
          label="Top Category"
          value={`${topCategory.icon} ${topCategory.name}`}
          sub={formatMoney(topCategory.amount)}
        />
        <HighlightCard
          icon={<AlertTriangle size={20} className="text-[#d97706]" />}
          label="Unusual Spikes"
          value={unusualDays.length}
          sub={`${unusualDays.length} abnormal day${unusualDays.length !== 1 ? 's' : ''}`}
        />
      </div>

      <div className="grid lg:grid-cols-2 gap-5">
        <div className="rounded-2xl bg-[#ffffff] border border-[#e7e4da] p-5 shadow-[0_2px_12px_rgba(27,67,50,0.03)]">
          <h2 className="text-sm font-bold text-[#14261c] mb-0.5">Daily Outflow Cadence</h2>
          <p className="text-xs text-[#6e8074] mb-4 font-medium">High spikes highlighted in crimson</p>
          <ResponsiveContainer width="100%" height={210}>
            <BarChart data={dailySpend} margin={{ top: 5, right: 5, bottom: 0, left: 0 }}>
              <XAxis dataKey="label" tick={{ fill: '#7d8e84', fontSize: 9 }} tickLine={false} axisLine={false} interval={4} />
              <YAxis tick={{ fill: '#7d8e84', fontSize: 10 }} tickLine={false} axisLine={false} tickFormatter={v => `$${v}`} />
              <Tooltip
                contentStyle={{ background: '#ffffff', border: '1px solid #d5ded7', borderRadius: 12, boxShadow: '0 4px 12px rgba(0,0,0,0.08)' }}
                formatter={(v) => [formatMoney(v), 'Spent']}
              />
              <Bar dataKey="total" radius={[4, 4, 0, 0]}>
                {dailySpend.map((d, i) => (
                  <Cell key={i} fill={d.total > avgDailySpend * 1.5 ? '#dc2626' : '#1b4332'} />
                ))}
              </Bar>
            </BarChart>
          </ResponsiveContainer>
        </div>

        <div className="rounded-2xl bg-[#ffffff] border border-[#e7e4da] p-5 shadow-[0_2px_12px_rgba(27,67,50,0.03)] flex flex-col justify-between">
          <div>
            <h2 className="text-sm font-bold text-[#14261c] mb-0.5">Category Proportions</h2>
            <p className="text-xs text-[#6e8074] mb-2 font-medium">Visual distribution across buckets</p>
          </div>
          <ResponsiveContainer width="100%" height={200}>
            <PieChart>
              <Pie data={catTotals} dataKey="amount" nameKey="name" cx="50%" cy="50%" outerRadius={78} innerRadius={42} paddingAngle={3}>
                {catTotals.map((entry, i) => (
                  <Cell key={i} fill={entry.color || CHART_COLORS[i % CHART_COLORS.length]} />
                ))}
              </Pie>
              <Tooltip formatter={(v) => formatMoney(v)} contentStyle={{ background: '#ffffff', border: '1px solid #d5ded7', borderRadius: 12 }} />
            </PieChart>
          </ResponsiveContainer>
        </div>
      </div>

      <div className="rounded-2xl bg-[#ffffff] border border-[#e7e4da] p-5 shadow-[0_2px_12px_rgba(27,67,50,0.03)]">
        <div className="flex items-center gap-2 mb-4">
          <TrendingUp size={18} className="text-[#1b4332]" />
          <h2 className="text-sm font-bold text-[#14261c]">Monthly Habit Scores</h2>
        </div>
        <div className="space-y-4">
          {[
            {
              label: 'Budget Discipline',
              value: Math.min(100, ((monthlyIncome - totalSpent) / monthlyIncome) * 100 + 50),
              good: true,
              desc: totalSpent <= monthlyIncome ? 'Maintained within monthly income targets' : 'Overspent beyond initial limits',
            },
            {
              label: 'Savings Rate Score',
              value: monthlyIncome > 0 ? (savings / monthlyIncome) * 100 : 0,
              good: savings / monthlyIncome > 0.2,
              desc: `${((savings / monthlyIncome) * 100).toFixed(1)}% of gross income retained`,
            },
            {
              label: 'Stability / Low Spike Consistency',
              value: dailySpend.length > 0 ? Math.max(0, 100 - (unusualDays.length / dailySpend.length) * 100) : 100,
              good: unusualDays.length < 3,
              desc: unusualDays.length === 0 ? 'No abnormal outflow anomalies recorded' : `${unusualDays.length} high spike day${unusualDays.length > 1 ? 's' : ''}`,
            },
          ].map((m, i) => (
            <div key={i}>
              <div className="flex items-center justify-between mb-1.5">
                <span className="text-xs font-bold text-[#14261c]">{m.label}</span>
                <div className="flex items-center gap-2">
                  <span className="text-xs text-[#718578] font-medium">{m.desc}</span>
                  <span className={`text-xs font-extrabold ${m.good ? 'text-[#1b4332]' : 'text-[#dc2626]'}`}>
                    {Math.round(Math.min(100, Math.max(0, m.value)))}%
                  </span>
                </div>
              </div>
              <div className="h-2.5 bg-[#f3efe5] rounded-full overflow-hidden p-0.5">
                <div
                  className="h-full rounded-full transition-all duration-700"
                  style={{
                    width: `${Math.min(100, Math.max(0, m.value))}%`,
                    backgroundColor: m.good ? '#1b4332' : '#dc2626',
                  }}
                />
              </div>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}

function HighlightCard({ icon, label, value, sub }) {
  return (
    <div className="rounded-2xl bg-[#ffffff] border border-[#e8e4da] p-4 shadow-xs">
      <div className="mb-2">{icon}</div>
      <p className="text-xs text-[#6e8074] mb-1 font-bold uppercase tracking-wider">{label}</p>
      <p className="text-base font-extrabold text-[#14261c] truncate">{value}</p>
      <p className="text-xs text-[#718578] font-medium mt-0.5">{sub}</p>
    </div>
  );
}
